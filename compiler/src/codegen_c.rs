//! Emit C from HIR v0 (ADR-0007 / ADR-0008). By-ref params: ADR-0005.

use crate::hir::{
    ArrayBound, BinOp, Block, Decl, Expr, FormatItem, Module, OnAction, Proc, Stmt, Storage, Type,
};
use crate::lex::eq_ignore_ascii_case;
use std::collections::{HashMap, HashSet};
use std::fmt::Write as _;
use std::sync::atomic::{AtomicU32, Ordering};

static SELECT_TMP: AtomicU32 = AtomicU32::new(0);
static DO_BY_TMP: AtomicU32 = AtomicU32::new(0);
static ON_EF_TMP: AtomicU32 = AtomicU32::new(0);

pub struct EmitOptions {
    pub emit_line: bool,
}

impl Default for EmitOptions {
    fn default() -> Self {
        Self { emit_line: true }
    }
}

struct Ctx<'a> {
    path: &'a str,
    opts: &'a EmitOptions,
    /// Names that are by-ref parameters in the current procedure.
    params: HashSet<String>,
    types: HashMap<String, Type>,
    dims: HashMap<String, Vec<ArrayBound>>,
    /// BASED var → locator pointer name.
    based: HashMap<String, String>,
    /// DEFINED overlay → base name.
    defined: HashMap<String, String>,
    /// Scalars in declaration order for PUT/GET DATA without a name list.
    data_names: Vec<String>,
    is_main: bool,
}

pub fn emit_c(module: &Module, opts: &EmitOptions) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "/* Generated by pl1c — PL/I-G */");
    let _ = writeln!(out, "#include <pl1rt.h>");
    let _ = writeln!(out, "#include <setjmp.h>");
    let _ = writeln!(out, "#include <stdlib.h>");
    let _ = writeln!(out, "#include <string.h>");
    let _ = writeln!(out);

    // Forward declarations for non-main procs.
    for proc in &module.procs {
        if proc.is_main {
            continue;
        }
        emit_proc_proto(&mut out, proc);
        let _ = writeln!(out, ";");
    }
    let _ = writeln!(out);

    // Emit non-main procedure bodies first.
    for proc in &module.procs {
        if proc.is_main {
            continue;
        }
        emit_proc_fn(&mut out, proc, &module.source_path, opts);
        let _ = writeln!(out);
    }

    let main = module
        .procs
        .iter()
        .find(|p| p.is_main)
        .expect("sema guarantees MAIN");

    let _ = writeln!(out, "int main(void) {{");
    emit_locals(&mut out, main);
    let ctx = Ctx {
        path: &module.source_path,
        opts,
        params: HashSet::new(),
        types: types_from_decls(&main.body.decls),
        dims: dims_from_decls(&main.body.decls),
        based: based_from_decls(&main.body.decls),
        defined: defined_from_decls(&main.body.decls),
        data_names: data_names_from_decls(&main.body.decls),
        is_main: true,
    };
    for stmt in &main.body.stmts {
        emit_stmt(&mut out, stmt, &ctx);
    }
    let _ = writeln!(out, "    return 0;");
    let _ = writeln!(out, "}}");
    out
}

fn types_from_decls(decls: &[Decl]) -> HashMap<String, Type> {
    let mut types = HashMap::new();
    for d in decls {
        types.insert(d.name.to_ascii_uppercase(), d.ty.clone());
    }
    types
}

fn dims_from_decls(decls: &[Decl]) -> HashMap<String, Vec<ArrayBound>> {
    let mut dims = HashMap::new();
    for d in decls {
        if let Some(dd) = &d.dims {
            dims.insert(d.name.to_ascii_uppercase(), dd.clone());
        }
    }
    dims
}

fn based_from_decls(decls: &[Decl]) -> HashMap<String, String> {
    let mut based = HashMap::new();
    for d in decls {
        if let Some(p) = &d.based_on {
            based.insert(d.name.to_ascii_uppercase(), p.clone());
        }
    }
    based
}

fn defined_from_decls(decls: &[Decl]) -> HashMap<String, String> {
    let mut defined = HashMap::new();
    for d in decls {
        if let Some(b) = &d.defined_on {
            defined.insert(d.name.to_ascii_uppercase(), b.clone());
        }
    }
    defined
}

fn merge_based(outer: &HashMap<String, String>, decls: &[Decl]) -> HashMap<String, String> {
    let mut based = outer.clone();
    for d in decls {
        let key = d.name.to_ascii_uppercase();
        if let Some(p) = &d.based_on {
            based.insert(key, p.clone());
        } else {
            based.remove(&key);
        }
    }
    based
}

fn merge_defined(outer: &HashMap<String, String>, decls: &[Decl]) -> HashMap<String, String> {
    let mut defined = outer.clone();
    for d in decls {
        let key = d.name.to_ascii_uppercase();
        if let Some(b) = &d.defined_on {
            defined.insert(key, b.clone());
        } else {
            defined.remove(&key);
        }
    }
    defined
}

fn data_names_from_decls(decls: &[Decl]) -> Vec<String> {
    let mut names = Vec::new();
    for d in decls {
        if d.dims.is_some() {
            continue;
        }
        if matches!(d.storage, Storage::Based) || d.based_on.is_some() || d.defined_on.is_some()
        {
            continue;
        }
        if matches!(
            d.ty,
            Type::FixedBin { .. } | Type::Float | Type::Char { .. }
        ) {
            names.push(d.name.clone());
        }
    }
    names
}

fn merge_data_names(outer: &[String], decls: &[Decl]) -> Vec<String> {
    let added = data_names_from_decls(decls);
    let added_keys: HashSet<String> = added.iter().map(|n| n.to_ascii_uppercase()).collect();
    let mut names: Vec<String> = outer
        .iter()
        .filter(|n| !added_keys.contains(&n.to_ascii_uppercase()))
        .cloned()
        .collect();
    names.extend(added);
    names
}

fn bound_len(b: &ArrayBound) -> i64 {
    match b {
        ArrayBound::Upper(n) => *n,
        ArrayBound::Range { from, to } => to - from + 1,
    }
}

fn bound_origin(b: &ArrayBound) -> i64 {
    match b {
        ArrayBound::Upper(_) => 1,
        ArrayBound::Range { from, .. } => *from,
    }
}

fn array_total_len(dims: &[ArrayBound]) -> i64 {
    dims.iter().map(bound_len).product()
}

fn emit_proc_proto(out: &mut String, proc: &Proc) {
    let fname = c_proc(&proc.name);
    let _ = write!(out, "static void {fname}(");
    if proc.params.is_empty() {
        let _ = write!(out, "void");
    } else {
        for (i, p) in proc.params.iter().enumerate() {
            if i > 0 {
                let _ = write!(out, ", ");
            }
            let ty = proc
                .body
                .decls
                .iter()
                .find(|d| eq_ignore_ascii_case(&d.name, p))
                .map(|d| &d.ty);
            match ty {
                Some(Type::Char { .. }) => {
                    let _ = write!(out, "char *{}", c_ident(p));
                }
                _ => {
                    let _ = write!(out, "int *{}", c_ident(p));
                }
            }
        }
    }
    let _ = write!(out, ")");
}

fn emit_proc_fn(out: &mut String, proc: &Proc, path: &str, opts: &EmitOptions) {
    emit_proc_proto(out, proc);
    let _ = writeln!(out, " {{");
    for d in &proc.body.decls {
        if matches!(d.storage, Storage::Parameter) {
            continue;
        }
        if proc
            .params
            .iter()
            .any(|p| eq_ignore_ascii_case(p, &d.name))
        {
            continue;
        }
        emit_decl(out, d);
    }
    let mut params = HashSet::new();
    for p in &proc.params {
        params.insert(p.to_ascii_uppercase());
    }
    let ctx = Ctx {
        path,
        opts,
        params,
        types: types_from_decls(&proc.body.decls),
        dims: dims_from_decls(&proc.body.decls),
        based: based_from_decls(&proc.body.decls),
        defined: defined_from_decls(&proc.body.decls),
        data_names: data_names_from_decls(&proc.body.decls),
        is_main: false,
    };
    for stmt in &proc.body.stmts {
        emit_stmt(out, stmt, &ctx);
    }
    let _ = writeln!(out, "}}");
}

fn emit_locals(out: &mut String, proc: &Proc) {
    let decls = &proc.body.decls;
    let mut i = 0;
    while i < decls.len() {
        let d = &decls[i];
        if matches!(d.storage, Storage::Parameter) {
            i += 1;
            continue;
        }
        if d.level == Some(1) && matches!(d.ty, Type::Struct) {
            let static_kw = match d.storage {
                Storage::Static => "static ",
                _ => "",
            };
            let Some(src_idx) = resolve_struct_base(decls, &d.name) else {
                i += 1;
                continue;
            };
            let mut j = src_idx + 1;
            let items = parse_struct_items(decls, &mut j, 1);
            // Skip this major's trailing members in the decl stream.
            i += 1;
            if d.like_of.is_none() {
                while i < decls.len() {
                    match decls[i].level {
                        Some(lev) if lev > 1 => i += 1,
                        _ => break,
                    }
                }
            }
            if d.based_on.is_some() {
                let tname = c_struct_ty(&d.name);
                emit_struct_type(out, &items, &tname, 1, StructEmit::Typedef);
            } else {
                let cname = c_ident(&d.name);
                let _ = write!(out, "    {static_kw}");
                emit_struct_type(out, &items, &cname, 1, StructEmit::Var);
            }
            continue;
        }
        if matches!(d.level, Some(lev) if lev > 1) {
            // Consumed with major STRUCTURE.
            i += 1;
            continue;
        }
        emit_decl(out, d);
        i += 1;
    }
}

enum StructItem<'a> {
    Elem { name: &'a str, ty: &'a Type },
    Minor { name: &'a str, kids: Vec<StructItem<'a>> },
}

fn resolve_struct_base(decls: &[Decl], major: &str) -> Option<usize> {
    let mut seen = HashSet::new();
    let mut name = major.to_ascii_uppercase();
    loop {
        if !seen.insert(name.clone()) {
            return None;
        }
        let idx = decls.iter().position(|d| {
            d.level == Some(1)
                && matches!(d.ty, Type::Struct)
                && d.name.eq_ignore_ascii_case(&name)
        })?;
        if let Some(src) = &decls[idx].like_of {
            name = src.to_ascii_uppercase();
            continue;
        }
        return Some(idx);
    }
}

fn parse_struct_items<'a>(
    decls: &'a [Decl],
    i: &mut usize,
    parent_level: u32,
) -> Vec<StructItem<'a>> {
    let mut items = Vec::new();
    while *i < decls.len() {
        let Some(lev) = decls[*i].level else {
            break;
        };
        if lev <= parent_level {
            break;
        }
        if lev != parent_level + 1 {
            // Skip malformed gaps rather than looping forever.
            *i += 1;
            continue;
        }
        let d = &decls[*i];
        *i += 1;
        if matches!(d.ty, Type::Struct) {
            let kids = parse_struct_items(decls, i, lev);
            items.push(StructItem::Minor {
                name: d.name.as_str(),
                kids,
            });
        } else {
            items.push(StructItem::Elem {
                name: d.name.as_str(),
                ty: &d.ty,
            });
        }
    }
    items
}

fn c_struct_ty(name: &str) -> String {
    format!("pl1_ty_{}", name.to_ascii_lowercase())
}

enum StructEmit {
    /// `struct { … } name = {0};`
    Var,
    /// nested `struct { … } name;`
    Nested,
    /// `typedef struct { … } name;`
    Typedef,
}

fn emit_struct_type(
    out: &mut String,
    items: &[StructItem<'_>],
    cname: &str,
    indent: usize,
    mode: StructEmit,
) {
    let pad = "    ".repeat(indent);
    match mode {
        StructEmit::Typedef => {
            let _ = write!(out, "{pad}typedef struct {{\n");
        }
        _ => {
            let _ = writeln!(out, "struct {{");
        }
    }
    for it in items {
        match it {
            StructItem::Elem { name, ty } => {
                let fname = c_ident(name);
                match ty {
                    Type::FixedBin { .. } => {
                        let _ = writeln!(out, "{pad}    int {fname};");
                    }
                    Type::Float => {
                        let _ = writeln!(out, "{pad}    double {fname};");
                    }
                    Type::Char { len } => {
                        let bytes = *len as usize + 1;
                        let _ = writeln!(out, "{pad}    char {fname}[{bytes}];");
                    }
                    _ => unreachable!("member type rejected earlier"),
                }
            }
            StructItem::Minor { name, kids } => {
                let fname = c_ident(name);
                let _ = write!(out, "{pad}    ");
                emit_struct_type(out, kids, &fname, indent + 1, StructEmit::Nested);
            }
        }
    }
    match mode {
        StructEmit::Var => {
            let _ = writeln!(out, "{pad}}} {cname} = {{0}};");
        }
        StructEmit::Nested => {
            let _ = writeln!(out, "{pad}}} {cname};");
        }
        StructEmit::Typedef => {
            let _ = writeln!(out, "{pad}}} {cname};");
        }
    }
}

fn emit_decl(out: &mut String, d: &Decl) {
    if matches!(d.storage, Storage::Based) || d.based_on.is_some() {
        // BASED: no automatic storage; ALLOCATE sets the locator.
        return;
    }
    if d.defined_on.is_some() {
        // DEFINED: overlay; storage is the base variable.
        return;
    }
    let cname = c_ident(&d.name);
    let static_kw = match d.storage {
        Storage::Static => "static ",
        Storage::Automatic | Storage::Parameter | Storage::Based => "",
    };
    if let Some(dims) = &d.dims {
        let n = array_total_len(dims);
        match &d.ty {
            Type::FixedBin { .. } => {
                if let Some(vals) = &d.init {
                    let parts: Vec<String> = vals
                        .iter()
                        .map(|e| match e {
                            Expr::IntLit(v) => v.to_string(),
                            Expr::FloatLit(v) => format!("(int)({})", c_float(*v)),
                            _ => "0".into(),
                        })
                        .collect();
                    let _ = writeln!(
                        out,
                        "    {static_kw}int {cname}[{n}] = {{{}}};",
                        parts.join(", ")
                    );
                } else {
                    let _ = writeln!(out, "    {static_kw}int {cname}[{n}] = {{0}};");
                }
            }
            Type::Float => {
                if let Some(vals) = &d.init {
                    let parts: Vec<String> = vals
                        .iter()
                        .map(|e| match e {
                            Expr::FloatLit(v) => c_float(*v),
                            Expr::IntLit(v) => format!("{v}.0"),
                            _ => "0.0".into(),
                        })
                        .collect();
                    let _ = writeln!(
                        out,
                        "    {static_kw}double {cname}[{n}] = {{{}}};",
                        parts.join(", ")
                    );
                } else {
                    let _ = writeln!(out, "    {static_kw}double {cname}[{n}] = {{0}};");
                }
            }
            Type::Char { len } => {
                let bytes = *len as usize + 1;
                if let Some(vals) = &d.init {
                    let parts: Vec<String> = vals
                        .iter()
                        .map(|e| match e {
                            Expr::StringLit(s) => {
                                let padded = pad_char_init(s, *len as usize);
                                format!("\"{}\"", c_escape(&padded))
                            }
                            _ => "\"\"".into(),
                        })
                        .collect();
                    let _ = writeln!(
                        out,
                        "    {static_kw}char {cname}[{n}][{bytes}] = {{{}}};",
                        parts.join(", ")
                    );
                } else {
                    let _ = writeln!(
                        out,
                        "    {static_kw}char {cname}[{n}][{bytes}] = {{{{0}}}};"
                    );
                }
            }
            _ => unreachable!("array elem type rejected earlier"),
        }
        return;
    }
    match &d.ty {
        Type::FixedBin { .. } => {
            let init = match d.init.as_deref() {
                Some([Expr::IntLit(n)]) => n.to_string(),
                Some([Expr::FloatLit(n)]) => format!("(int)({})", c_float(*n)),
                _ => "0".to_string(),
            };
            let _ = writeln!(out, "    {static_kw}int {cname} = {init};");
        }
        Type::Float => {
            let init = match d.init.as_deref() {
                Some([Expr::FloatLit(n)]) => c_float(*n),
                Some([Expr::IntLit(n)]) => format!("{n}.0"),
                _ => "0.0".to_string(),
            };
            let _ = writeln!(out, "    {static_kw}double {cname} = {init};");
        }
        Type::Char { len } => {
            let n = *len as usize;
            let bytes = n + 1;
            match d.init.as_deref() {
                Some([Expr::StringLit(s)]) => {
                    let padded = pad_char_init(s, n);
                    let esc = c_escape(&padded);
                    let _ = writeln!(
                        out,
                        "    {static_kw}char {cname}[{bytes}] = \"{esc}\";"
                    );
                }
                _ => {
                    let _ = writeln!(out, "    {static_kw}char {cname}[{bytes}] = {{0}};");
                }
            }
        }
        Type::Pointer => {
            let init = match d.init.as_deref() {
                Some([Expr::Null]) => "NULL",
                _ => "NULL",
            };
            let _ = writeln!(out, "    {static_kw}void *{cname} = {init};");
        }
        Type::Bit { .. } => {
            let init = match d.init.as_deref() {
                Some([Expr::IntLit(n)]) => ((*n != 0) as u8).to_string(),
                Some([Expr::BitLit { value, .. }]) => value.to_string(),
                _ => "0".into(),
            };
            let _ = writeln!(out, "    {static_kw}unsigned char {cname} = {init};");
        }
        Type::Struct => {
            unreachable!("STRUCT without level rejected before codegen");
        }
    }
}

fn c_float(n: f64) -> String {
    let s = format!("{n}");
    if s.contains('.') || s.contains('e') || s.contains('E') {
        s
    } else {
        format!("{s}.0")
    }
}

fn pad_char_init(s: &str, len: usize) -> String {
    let mut out: String = s.chars().take(len).collect();
    while out.chars().count() < len {
        out.push(' ');
    }
    out
}

fn emit_block(out: &mut String, body: &Block, ctx: &Ctx) {
    let _ = writeln!(out, "    {{");
    for d in &body.decls {
        emit_decl(out, d);
    }
    let mut nested = ctx.types.clone();
    let mut nested_dims = ctx.dims.clone();
    for d in &body.decls {
        let key = d.name.to_ascii_uppercase();
        nested.insert(key.clone(), d.ty.clone());
        if let Some(dd) = &d.dims {
            nested_dims.insert(key, dd.clone());
        } else {
            nested_dims.remove(&key);
        }
    }
    let nested_ctx = Ctx {
        path: ctx.path,
        opts: ctx.opts,
        params: ctx.params.clone(),
        types: nested,
        dims: nested_dims,
        based: merge_based(&ctx.based, &body.decls),
        defined: merge_defined(&ctx.defined, &body.decls),
        data_names: merge_data_names(&ctx.data_names, &body.decls),
        is_main: ctx.is_main,
    };
    for stmt in &body.stmts {
        emit_stmt(out, stmt, &nested_ctx);
    }
    let _ = writeln!(out, "    }}");
}

fn c_ident(name: &str) -> String {
    format!("pl1_{}", name.to_ascii_lowercase())
}

fn c_label(name: &str) -> String {
    format!("pl1_lab_{}", name.to_ascii_lowercase())
}

fn c_proc(name: &str) -> String {
    format!("pl1_proc_{}", name.to_ascii_lowercase())
}

fn is_param(ctx: &Ctx, name: &str) -> bool {
    ctx.params.contains(&name.to_ascii_uppercase())
}

fn lookup_ty<'a>(ctx: &'a Ctx, name: &str) -> Option<&'a Type> {
    ctx.types.get(&name.to_ascii_uppercase())
}

fn lookup_dims<'a>(ctx: &'a Ctx, name: &str) -> Option<&'a [ArrayBound]> {
    ctx.dims.get(&name.to_ascii_uppercase()).map(|d| d.as_slice())
}

/// Flattened C index for PL/I subscripts (row-major, PL/I origin → 0-based).
fn array_c_index(ctx: &Ctx, name: &str, indices: &[Expr]) -> String {
    let dims = lookup_dims(ctx, name).expect("sema guarantees array dims");
    debug_assert_eq!(dims.len(), indices.len());
    let mut parts = Vec::new();
    let mut stride = 1i64;
    // Precompute strides from the right.
    let mut strides = vec![1i64; dims.len()];
    for i in (0..dims.len().saturating_sub(1)).rev() {
        stride *= bound_len(&dims[i + 1]);
        strides[i] = stride;
    }
    for (i, (idx, bound)) in indices.iter().zip(dims.iter()).enumerate() {
        let e = emit_expr(idx, ctx);
        let origin = bound_origin(bound);
        let term = if strides[i] == 1 {
            format!("(({e}) - {origin})")
        } else {
            format!("((({e}) - {origin}) * {})", strides[i])
        };
        parts.push(term);
    }
    parts.join(" + ")
}

fn array_elem(ctx: &Ctx, name: &str, indices: &[Expr]) -> String {
    let base = c_ident(name);
    let idx = array_c_index(ctx, name, indices);
    format!("{base}[{idx}]")
}

fn lvalue(ctx: &Ctx, name: &str) -> String {
    let key = name.to_ascii_uppercase();
    if let Some(base) = ctx.defined.get(&key) {
        return lvalue(ctx, base);
    }
    if let Some(ptr) = ctx.based.get(&key) {
        let p = c_ident(ptr);
        return match lookup_ty(ctx, name) {
            Some(Type::FixedBin { .. }) => format!("(*(int *){p})"),
            Some(Type::Float) => format!("(*(double *){p})"),
            Some(Type::Char { .. }) => format!("((char *){p})"),
            Some(Type::Bit { .. }) => format!("(*(unsigned char *){p})"),
            _ => format!("(*{p})"),
        };
    }
    let id = c_ident(name);
    if is_param(ctx, name) {
        match lookup_ty(ctx, name) {
            Some(Type::Char { .. }) => id, // char* parameter decays
            _ => format!("(*{id})"),
        }
    } else {
        id
    }
}

fn based_locator<'a>(ctx: &'a Ctx, name: &str) -> Option<&'a str> {
    ctx.based
        .get(&name.to_ascii_uppercase())
        .map(|s| s.as_str())
}

fn alloc_size_expr(ctx: &Ctx, name: &str) -> String {
    match lookup_ty(ctx, name) {
        Some(Type::FixedBin { .. }) => "sizeof(int)".into(),
        Some(Type::Float) => "sizeof(double)".into(),
        Some(Type::Char { len }) => format!("((size_t){} + 1)", len),
        Some(Type::Bit { .. }) => "sizeof(unsigned char)".into(),
        Some(Type::Struct) => format!("sizeof({})", c_struct_ty(name)),
        _ => unreachable!("ALLOCATE type rejected earlier"),
    }
}

fn field_lvalue(ctx: &Ctx, path: &[String]) -> String {
    let mut parts = path.iter().map(|p| c_ident(p));
    let head_name = path.first().map(|s| s.as_str()).unwrap_or("?");
    let head = parts.next().unwrap_or_else(|| "pl1_?".into());
    let rest: Vec<String> = parts.collect();
    if let Some(ptr) = based_locator(ctx, head_name) {
        let ty = c_struct_ty(head_name);
        let p = c_ident(ptr);
        if rest.is_empty() {
            format!("(*({ty} *){p})")
        } else {
            format!("(({ty} *){p})->{}", rest.join("."))
        }
    } else if rest.is_empty() {
        head
    } else {
        format!("{head}.{}", rest.join("."))
    }
}

fn char_len(ctx: &Ctx, name: &str) -> Option<u32> {
    match lookup_ty(ctx, name) {
        Some(Type::Char { len }) => Some(*len),
        _ => None,
    }
}

fn emit_stmt(out: &mut String, stmt: &Stmt, ctx: &Ctx) {
    match stmt {
        Stmt::Labeled { labels, body } => {
            for lab in labels {
                let _ = writeln!(out, "{}:", c_label(lab));
            }
            emit_stmt(out, body, ctx);
        }
        Stmt::AssignField { path, value } => {
            if ctx.opts.emit_line {
                let _ = writeln!(out, "    /* assign field from {} */", ctx.path);
            }
            let lhs = field_lvalue(ctx, path);
            let mem = path.last().map(|s| s.as_str()).unwrap_or("");
            if let Some(n) = char_len(ctx, mem) {
                match value {
                    Expr::StringLit(s) => {
                        let esc = c_escape(s);
                        let _ = writeln!(
                            out,
                            "    pl1rt_char_assign({lhs}, {n}, \"{esc}\");"
                        );
                    }
                    other => {
                        let src = emit_expr(other, ctx);
                        let _ = writeln!(out, "    pl1rt_char_assign({lhs}, {n}, {src});");
                    }
                }
            } else {
                let rhs = emit_expr(value, ctx);
                let rhs = match lookup_ty(ctx, mem) {
                    Some(Type::FixedBin { .. }) if expr_is_floaty(value, ctx) => {
                        format!("(int)({rhs})")
                    }
                    Some(Type::Float) if !expr_is_floaty(value, ctx) => {
                        format!("(double)({rhs})")
                    }
                    _ => rhs,
                };
                let _ = writeln!(out, "    {lhs} = {rhs};");
            }
        }
        Stmt::Assign { name, value } => {
            if ctx.opts.emit_line {
                let _ = writeln!(out, "    /* assign from {} */", ctx.path);
            }
            if let (Some(dd), Expr::Name(src)) = (lookup_dims(ctx, name), value) {
                let n = array_total_len(dd);
                let dst = c_ident(name);
                let src_id = c_ident(src);
                match lookup_ty(ctx, name) {
                    Some(Type::FixedBin { .. }) => {
                        let _ = writeln!(
                            out,
                            "    memcpy({dst}, {src_id}, sizeof(int) * {n});"
                        );
                    }
                    Some(Type::Float) => {
                        let _ = writeln!(
                            out,
                            "    memcpy({dst}, {src_id}, sizeof(double) * {n});"
                        );
                    }
                    Some(Type::Char { len }) => {
                        let bytes = *len as usize + 1;
                        let _ = writeln!(
                            out,
                            "    memcpy({dst}, {src_id}, {bytes} * {n});"
                        );
                    }
                    _ => unreachable!("aggregate assign types checked in sema"),
                }
                return;
            }
            if matches!(lookup_ty(ctx, name), Some(Type::Struct)) {
                let Expr::Name(src) = value else {
                    unreachable!("sema requires STRUCTURE RHS");
                };
                let dst = c_ident(name);
                let src_id = c_ident(src);
                let _ = writeln!(
                    out,
                    "    memcpy(&{dst}, &{src_id}, sizeof({dst}));"
                );
                return;
            }
            if let Some(n) = char_len(ctx, name) {
                let dst = lvalue(ctx, name);
                match value {
                    Expr::StringLit(s) => {
                        let esc = c_escape(s);
                        let _ = writeln!(
                            out,
                            "    pl1rt_char_assign({dst}, {n}, \"{esc}\");"
                        );
                    }
                    Expr::Name(src) => {
                        let src_id = lvalue(ctx, src);
                        if let Some(src_n) = char_len(ctx, src) {
                            let _ = writeln!(
                                out,
                                "    pl1rt_char_assign_n({dst}, {n}, {src_id}, {src_n});"
                            );
                        } else {
                            let _ = writeln!(
                                out,
                                "    pl1rt_char_assign({dst}, {n}, {src_id});"
                            );
                        }
                    }
                    _ => unreachable!("sema rejects non-CHAR RHS for CHAR"),
                }
                return;
            }
            let lhs = lvalue(ctx, name);
            let rhs = emit_expr(value, ctx);
            let rhs = match lookup_ty(ctx, name) {
                Some(Type::FixedBin { .. }) if expr_is_floaty(value, ctx) => {
                    format!("(int)({rhs})")
                }
                Some(Type::Float) if !expr_is_floaty(value, ctx) => {
                    format!("(double)({rhs})")
                }
                Some(Type::Bit { len }) => {
                    let mask = if *len >= 8 {
                        0xFFu64
                    } else {
                        (1u64 << len) - 1
                    };
                    format!("(unsigned char)(({rhs}) & {mask})")
                }
                _ => rhs,
            };
            let _ = writeln!(out, "    {lhs} = {rhs};");
        }
        Stmt::AssignIndex {
            name,
            indices,
            value,
        } => {
            if ctx.opts.emit_line {
                let _ = writeln!(out, "    /* assign index from {} */", ctx.path);
            }
            let lhs = array_elem(ctx, name, indices);
            if let Some(n) = char_len(ctx, name) {
                match value {
                    Expr::StringLit(s) => {
                        let esc = c_escape(s);
                        let _ = writeln!(
                            out,
                            "    pl1rt_char_assign({lhs}, {n}, \"{esc}\");"
                        );
                    }
                    Expr::Name(src) => {
                        let src_id = lvalue(ctx, src);
                        if let Some(src_n) = char_len(ctx, src) {
                            let _ = writeln!(
                                out,
                                "    pl1rt_char_assign_n({lhs}, {n}, {src_id}, {src_n});"
                            );
                        } else {
                            let _ = writeln!(
                                out,
                                "    pl1rt_char_assign({lhs}, {n}, {src_id});"
                            );
                        }
                    }
                    Expr::Index {
                        base: src,
                        indices: src_ix,
                    } => {
                        let src_id = array_elem(ctx, src, src_ix);
                        if let Some(src_n) = char_len(ctx, src) {
                            let _ = writeln!(
                                out,
                                "    pl1rt_char_assign_n({lhs}, {n}, {src_id}, {src_n});"
                            );
                        } else {
                            let _ = writeln!(
                                out,
                                "    pl1rt_char_assign({lhs}, {n}, {src_id});"
                            );
                        }
                    }
                    _ => unreachable!("sema rejects non-CHAR RHS for CHAR"),
                }
                return;
            }
            let rhs = emit_expr(value, ctx);
            let rhs = match lookup_ty(ctx, name) {
                Some(Type::FixedBin { .. }) if expr_is_floaty(value, ctx) => {
                    format!("(int)({rhs})")
                }
                Some(Type::Float) if !expr_is_floaty(value, ctx) => {
                    format!("(double)({rhs})")
                }
                _ => rhs,
            };
            let _ = writeln!(out, "    {lhs} = {rhs};");
        }
        Stmt::PutList { file, skip, items } => {
            emit_set_out(out, file.as_deref());
            if ctx.opts.emit_line {
                let _ = writeln!(out, "    /* put from {} */", ctx.path);
            }
            if *skip {
                let _ = writeln!(out, "    pl1rt_put_skip();");
            }
            for (i, item) in items.iter().enumerate() {
                if i > 0 {
                    let _ = writeln!(out, "    pl1rt_put_space();");
                }
                emit_put_item(out, item, ctx);
            }
            emit_clear_out(out, file.as_deref());
        }
        Stmt::If {
            cond,
            then_branch,
            else_branch,
        } => {
            let c = emit_expr(cond, ctx);
            let _ = writeln!(out, "    if ({c}) {{");
            emit_stmt(out, then_branch, ctx);
            let _ = writeln!(out, "    }}");
            if let Some(e) = else_branch {
                let _ = writeln!(out, "    else {{");
                emit_stmt(out, e, ctx);
                let _ = writeln!(out, "    }}");
            }
        }
        Stmt::DoCounted {
            var,
            from,
            to,
            step,
            body,
        } => {
            let v = lvalue(ctx, var);
            let f = emit_expr(from, ctx);
            let t = emit_expr(to, ctx);
            let s = step
                .as_ref()
                .map(|e| emit_expr(e, ctx))
                .unwrap_or_else(|| "1".to_string());
            // Negative BY → descending: compare with >= (classic counted DO).
            let by_id = DO_BY_TMP.fetch_add(1, Ordering::Relaxed);
            let by = format!("pl1_by_{by_id}");
            let _ = writeln!(out, "    {{");
            let _ = writeln!(out, "    int {by} = ({s});");
            let _ = writeln!(
                out,
                "    for ({v} = ({f}); ({by} >= 0) ? ({v} <= ({t})) : ({v} >= ({t})); {v} += {by}) {{"
            );
            for st in body {
                emit_stmt(out, st, ctx);
            }
            let _ = writeln!(out, "    }}");
            let _ = writeln!(out, "    }}");
        }
        Stmt::DoGroup { body } => {
            // do/while(0) so LEAVE can `break`
            let _ = writeln!(out, "    do {{");
            for st in body {
                emit_stmt(out, st, ctx);
            }
            let _ = writeln!(out, "    }} while (0);");
        }
        Stmt::DoWhile { cond, body } => {
            let c = emit_expr(cond, ctx);
            let _ = writeln!(out, "    while ({c}) {{");
            for st in body {
                emit_stmt(out, st, ctx);
            }
            let _ = writeln!(out, "    }}");
        }
        Stmt::DoUntil { cond, body } => {
            let c = emit_expr(cond, ctx);
            let _ = writeln!(out, "    do {{");
            for st in body {
                emit_stmt(out, st, ctx);
            }
            let _ = writeln!(out, "    }} while (!({c}));");
        }
        Stmt::Leave => {
            let _ = writeln!(out, "    break;");
        }
        Stmt::Iterate => {
            let _ = writeln!(out, "    continue;");
        }
        Stmt::Return => {
            if ctx.is_main {
                let _ = writeln!(out, "    return 0;");
            } else {
                let _ = writeln!(out, "    return;");
            }
        }
        Stmt::Stop => {
            let _ = writeln!(out, "    exit(0);");
        }
        Stmt::Goto { label } => {
            let _ = writeln!(out, "    goto {};", c_label(label));
        }
        Stmt::Null => {
            let _ = writeln!(out, "    ;");
        }
        Stmt::PutEdit {
            file,
            skip,
            items,
            formats,
        } => {
            emit_set_out(out, file.as_deref());
            emit_put_edit(out, *skip, items, formats, ctx);
            emit_clear_out(out, file.as_deref());
        }
        Stmt::GetEdit {
            file,
            skip,
            items,
            formats,
        } => {
            emit_set_in(out, file.as_deref());
            emit_get_edit(out, *skip, items, formats, ctx);
            emit_clear_in(out, file.as_deref());
        }
        Stmt::PutData { file, skip, items } => {
            emit_set_out(out, file.as_deref());
            let names = match items {
                Some(names) => names.as_slice(),
                None => ctx.data_names.as_slice(),
            };
            emit_put_data(out, *skip, names, ctx);
            emit_clear_out(out, file.as_deref());
        }
        Stmt::GetData { file, skip, items } => {
            emit_set_in(out, file.as_deref());
            match items {
                Some(names) => emit_get_data(out, *skip, names, ctx),
                None => emit_get_data_all(out, *skip, ctx),
            }
            emit_clear_in(out, file.as_deref());
        }
        Stmt::GetList { file, skip, items } => {
            emit_set_in(out, file.as_deref());
            if ctx.opts.emit_line {
                let _ = writeln!(out, "    /* get from {} */", ctx.path);
            }
            if *skip {
                let _ = writeln!(out, "    pl1rt_get_skip();");
            }
            for name in items {
                match lookup_ty(ctx, name) {
                    Some(Type::FixedBin { .. }) => {
                        let id = lvalue(ctx, name);
                        let _ = writeln!(out, "    {id} = pl1rt_get_i32();");
                    }
                    Some(Type::Float) => {
                        let id = lvalue(ctx, name);
                        let _ = writeln!(out, "    {id} = pl1rt_get_f64();");
                    }
                    Some(Type::Char { len }) => {
                        let id = lvalue(ctx, name);
                        let _ = writeln!(out, "    pl1rt_get_char({id}, {len});");
                    }
                    _ => unreachable!("sema requires declared GET targets"),
                }
            }
            emit_clear_in(out, file.as_deref());
        }
        Stmt::Open {
            file,
            options,
            title,
        } => {
            let mode = open_mode(options);
            let path = title.as_deref().unwrap_or(file.as_str());
            let path_esc = c_escape(path);
            let _ = writeln!(
                out,
                "    pl1rt_fopen(\"{file}\", \"{path_esc}\", \"{mode}\");"
            );
        }
        Stmt::Close { file } => {
            let _ = writeln!(out, "    pl1rt_fclose(\"{file}\");");
        }
        Stmt::Call { name, args } => {
            let fname = c_proc(name);
            let mut parts = Vec::new();
            for a in args {
                match a {
                    Expr::Name(n) => {
                        if is_param(ctx, n) {
                            parts.push(c_ident(n)); // already a pointer
                        } else if matches!(lookup_ty(ctx, n), Some(Type::Char { .. })) {
                            parts.push(c_ident(n)); // array decays to pointer
                        } else {
                            parts.push(format!("&{}", c_ident(n)));
                        }
                    }
                    _ => unreachable!("sema requires Name args"),
                }
            }
            let _ = writeln!(out, "    {fname}({});", parts.join(", "));
        }
        Stmt::Begin { body } => emit_block(out, body, ctx),
        Stmt::Select {
            expr,
            whens,
            otherwise,
        } => emit_select(out, expr.as_ref(), whens, otherwise.as_deref(), ctx),
        Stmt::On {
            condition,
            refer,
            action,
        } => {
            if !eq_ignore_ascii_case(condition, "ENDFILE") {
                unreachable!("non-ENDFILE ON rejected before codegen");
            }
            let id = ON_EF_TMP.fetch_add(1, Ordering::Relaxed);
            let file = refer
                .as_deref()
                .map(|f| format!("\"{f}\""))
                .unwrap_or_else(|| "NULL".into());
            let _ = writeln!(out, "    {{");
            let _ = writeln!(out, "    static jmp_buf pl1_ef_jb_{id};");
            let _ = writeln!(out, "    if (setjmp(pl1_ef_jb_{id}) == 0) {{");
            let _ = writeln!(out, "    pl1rt_on_endfile({file}, &pl1_ef_jb_{id});");
            let _ = writeln!(out, "    }} else {{");
            match action {
                OnAction::Goto { label } => {
                    let lab = c_label(label);
                    let _ = writeln!(out, "    goto {lab};");
                }
                OnAction::Stmt(s) => emit_stmt(out, s, ctx),
                OnAction::System => {
                    let _ = writeln!(out, "    exit(1); /* ON … SYSTEM */");
                }
                OnAction::Snap { .. } | OnAction::Null => {
                    let _ = writeln!(out, "    ; /* ON … SNAP/null (L0 no-op) */");
                }
            }
            let _ = writeln!(out, "    }}");
            let _ = writeln!(out, "    }}");
        }
        Stmt::Revert { condition, refer } => {
            if !eq_ignore_ascii_case(condition, "ENDFILE") {
                unreachable!("non-ENDFILE REVERT rejected before codegen");
            }
            let file = refer
                .as_deref()
                .map(|f| format!("\"{f}\""))
                .unwrap_or_else(|| "NULL".into());
            let _ = writeln!(out, "    pl1rt_revert_endfile({file});");
        }
        Stmt::Signal { condition, refer } => {
            if !eq_ignore_ascii_case(condition, "ENDFILE") {
                unreachable!("non-ENDFILE SIGNAL rejected before codegen");
            }
            let file = refer
                .as_deref()
                .map(|f| format!("\"{f}\""))
                .unwrap_or_else(|| "NULL".into());
            let _ = writeln!(out, "    pl1rt_signal_endfile({file});");
        }
        Stmt::Allocate { name, set } => {
            if ctx.opts.emit_line {
                let _ = writeln!(out, "    /* allocate from {} */", ctx.path);
            }
            let ptr_name = set
                .as_deref()
                .or_else(|| based_locator(ctx, name))
                .expect("ALLOCATE requires SET or BASED(P)");
            let ptr = c_ident(ptr_name);
            let size = alloc_size_expr(ctx, name);
            let _ = writeln!(out, "    {ptr} = malloc({size});");
        }
        Stmt::Free { name } => {
            if ctx.opts.emit_line {
                let _ = writeln!(out, "    /* free from {} */", ctx.path);
            }
            let ptr_name = based_locator(ctx, name).expect("FREE requires BASED locator");
            let ptr = c_ident(ptr_name);
            let _ = writeln!(out, "    free({ptr});");
            let _ = writeln!(out, "    {ptr} = NULL;");
        }
    }
}

